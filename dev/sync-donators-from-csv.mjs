#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';

function usage() {
  console.log(
    [
      'Usage:',
      '  node dev/sync-donators-from-csv.mjs [options]',
      '',
      'Options:',
      '  --kofi-csv <path>',
      '  --twitch-csv <path>',
      '  --youtube-csv <path>',
      '  --streamelements-csv <path>',
      '  --out <path>                 (default: Donators/donators.json)',
      '',
      'Example:',
      '  node dev/sync-donators-from-csv.mjs --kofi-csv ./exports/kofi.csv --twitch-csv ./exports/twitch.csv'
    ].join('\n')
  );
}

function parseArgs(argv) {
  const out = {
    out: 'Donators/donators.json'
  };
  for (let i = 0; i < argv.length; i += 1) {
    const key = argv[i];
    const next = argv[i + 1];
    if (key === '--help' || key === '-h') {
      out.help = true;
      continue;
    }
    if (!key.startsWith('--')) continue;
    if (!next || next.startsWith('--')) continue;
    out[key.slice(2)] = next;
    i += 1;
  }
  return out;
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (ch === '"') {
      const next = text[i + 1];
      if (inQuotes && next === '"') {
        field += '"';
        i += 1;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }
    if (ch === ',' && !inQuotes) {
      row.push(field);
      field = '';
      continue;
    }
    if ((ch === '\n' || ch === '\r') && !inQuotes) {
      if (ch === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
      continue;
    }
    field += ch;
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  if (!rows.length) return [];

  const headers = rows[0].map((h) => String(h || '').trim());
  return rows
    .slice(1)
    .filter((r) => r.some((v) => String(v || '').trim() !== ''))
    .map((r) => {
      const item = {};
      headers.forEach((h, idx) => {
        item[h] = (r[idx] || '').trim();
      });
      return item;
    });
}

function getField(row, candidates) {
  const keys = Object.keys(row);
  for (const c of candidates) {
    const lower = c.toLowerCase();
    const key = keys.find((k) => k.toLowerCase() === lower);
    if (key && row[key]) return String(row[key]).trim();
  }
  return '';
}

function toSupporter(row, platform, defaults = {}) {
  const name =
    getField(row, ['name', 'display name', 'username', 'subscriber', 'supporter', 'from']) ||
    defaults.name ||
    'Anonymous';
  const amount = getField(row, ['amount', 'tip amount', 'total', 'pledge amount']) || defaults.amount || '';
  const currency = getField(row, ['currency']) || defaults.currency || '';
  const date = getField(row, ['date', 'created at', 'timestamp', 'subscribed at']) || defaults.date || '';
  const message = getField(row, ['message', 'note', 'comment']) || defaults.message || '';
  const kind =
    getField(row, ['kind', 'type', 'support type']) ||
    defaults.kind ||
    (platform === 'twitch' ? 'subscription' : 'donation');
  return { name, platform, kind, amount, currency, date, message };
}

async function readCsvAsSupporters(filePath, platform, defaults) {
  if (!filePath) return [];
  const text = await fs.readFile(filePath, 'utf8');
  const rows = parseCsv(text);
  return rows.map((r) => toSupporter(r, platform, defaults));
}

function dedupeSupporters(items) {
  const seen = new Set();
  const out = [];
  for (const item of items) {
    const key = [
      item.name || '',
      item.platform || '',
      item.kind || '',
      item.amount || '',
      item.currency || '',
      item.date || ''
    ]
      .join('|')
      .toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(item);
  }
  return out;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    usage();
    return;
  }

  const records = [];
  records.push(
    ...(await readCsvAsSupporters(args['kofi-csv'], 'kofi', { kind: 'donation' })),
    ...(await readCsvAsSupporters(args['twitch-csv'], 'twitch', { kind: 'subscription' })),
    ...(await readCsvAsSupporters(args['youtube-csv'], 'youtube', { kind: 'donation' })),
    ...(await readCsvAsSupporters(args['streamelements-csv'], 'streamelements', { kind: 'donation' }))
  );

  const supporters = dedupeSupporters(records);
  const outData = {
    updatedAt: new Date().toISOString().slice(0, 10),
    notes: 'Generated by dev/sync-donators-from-csv.mjs',
    supporters
  };

  const outPath = path.resolve(args.out || 'Donators/donators.json');
  await fs.mkdir(path.dirname(outPath), { recursive: true });
  await fs.writeFile(outPath, JSON.stringify(outData, null, 2) + '\n', 'utf8');
  console.log('Wrote ' + supporters.length + ' supporters to ' + outPath);
}

main().catch((err) => {
  console.error(err.message || err);
  process.exitCode = 1;
});
